import { TILE } from '../engine/constants.js';

// Временная карта Этапа 2: полигон для проверки ощущений. Она шире и выше экрана,
// поэтому камере есть что показывать, а в ней самой намеренно собраны все случаи,
// на которых платформер обычно и врёт: край платформы, провал, цепочка прыжков
// ровно на два тайла, лесенка и зигзаг вверх.
//
// Под зигзагом (колонки 51-59) пола нет намеренно. Сначала он там был, и это
// оказалось капканом: сорвавшись с платформы, игрок приземлялся живым в колодец
// со стеной в четыре тайла и не мог из него выбраться никаким прыжком. Правило
// теперь одно на всю карту — промахнулся мимо платформы, летишь вниз и
// возвращаешься на чекпоинт. Чекпоинт на верху лесенки (48, 15) для того и
// стоит, чтобы падение стоило одной попытки, а не всего пути.
//
// На Этапе 3 её заменит level.js, читающий levels/01.json — формат ASCII-строк
// специально тот же самый, чтобы замена была честной, а не переписыванием.

const LEGEND = {
  '#': 'ground',
  '=': 'platform',
  F: 'checkpoint',
  '.': 'empty'
};

// Пока сквозь платформы нельзя запрыгнуть снизу — они такие же твёрдые, как земля.
// Односторонние платформы это отдельная механика, ей место на Этапе 3.
const SOLID = new Set(['ground', 'platform']);

const ROWS = [
  '............................................................',
  '............................................................',
  '............................................................',
  '............................................................',
  '............................................................',
  '............................................................',
  '....................................................======..',
  '............................................................',
  '...............................................====.........',
  '............................................................',
  '....................................................====....',
  '............................................................',
  '...............................................====.........',
  '............................................................',
  '....................................................====....',
  '................................................F...........',
  '.........................====..................####.........',
  '...............................................####.........',
  '......====.........====....................########.........',
  '..............................F.........F..########.........',
  '##############..################..#################.........',
  '##############..################..#################.........'
];

export const testMap = {
  legend: LEGEND,
  rows: ROWS,
  columns: ROWS[0].length,
  lines: ROWS.length,
  widthPx: ROWS[0].length * TILE,
  heightPx: ROWS.length * TILE,
  spawn: [2, 18],

  tileAt(column, line) {
    const row = ROWS[line];
    if (!row) return 'empty';
    return LEGEND[row[column]] ?? 'empty';
  },

  isSolid(column, line) {
    // Края карты по бокам — невидимые стены, иначе игрок убежит в пустоту.
    // Сверху и снизу пусто: вверх можно прыгать, вниз — падать (и вернуться
    // на чекпоинт).
    if (column < 0 || column >= this.columns) return true;
    if (line < 0 || line >= this.lines) return false;
    return SOLID.has(this.tileAt(column, line));
  }
};
