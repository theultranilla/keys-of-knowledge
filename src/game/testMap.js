import { TILE } from '../engine/constants.js';

// Временная карта Этапа 1: нужна только чтобы было по чему бегать и прыгать.
// На Этапе 3 её заменит level.js, читающий levels/01.json — формат ASCII-строк
// специально тот же самый, чтобы замена была честной, а не переписыванием.

const LEGEND = {
  '#': 'ground',
  '=': 'platform',
  '.': 'empty'
};

// Пока сквозь платформы нельзя запрыгнуть снизу — они такие же твёрдые, как земля.
// Односторонние платформы это отдельная механика, ей место на Этапе 3.
const SOLID = new Set(['ground', 'platform']);

const ROWS = [
  '..............................',
  '..............................',
  '..............................',
  '......====....................',
  '..............................',
  '................=====.........',
  '..............................',
  '...====.......................',
  '..............................',
  '...........=====..............',
  '..............................',
  '#........................====#',
  '#............................#',
  '#.......####.................#',
  '#............................#',
  '#.......................######',
  '##############################'
];

export const testMap = {
  legend: LEGEND,
  rows: ROWS,
  columns: ROWS[0].length,
  lines: ROWS.length,
  widthPx: ROWS[0].length * TILE,
  heightPx: ROWS.length * TILE,
  spawn: [3, 14],

  tileAt(column, line) {
    const row = ROWS[line];
    if (!row) return 'empty';
    return LEGEND[row[column]] ?? 'empty';
  },

  isSolid(column, line) {
    // Края карты по бокам — невидимые стены, иначе игрок убежит в пустоту.
    // Сверху и снизу пусто: вверх можно прыгать, вниз — падать (и разбиться).
    if (column < 0 || column >= this.columns) return true;
    if (line < 0 || line >= this.lines) return false;
    return SOLID.has(this.tileAt(column, line));
  }
};
